function getUniqueBlogs(items) {
  const seen = new Set();

  return items.filter((item) => {
    const key = `${item.title}__${item.url}`;
    if (seen.has(key)) return false;

    seen.add(key);
    return true;
  });
}

function getBlogSource(title) {
  const separators = [" | ", " – ", " - "];

  for (const separator of separators) {
    if (!title.includes(separator)) continue;

    const parts = title.split(separator).map((part) => part.trim()).filter(Boolean);
    const source = parts[parts.length - 1];
    if (source && source.length <= 90) return source;
  }

  return "";
}

function renderBlogs(items) {
  if (!blogGrid) return;

  blogGrid.innerHTML = "";

  if (blogResultCount) {
    blogResultCount.textContent = `${items.length} ${items.length === 1 ? "article" : "articles"}`;
  }

  if (!items.length) {
    const empty = document.createElement("p");
    empty.className = "blog-empty";
    empty.textContent = "No matching blog titles found.";
    blogGrid.appendChild(empty);
    return;
  }

  items.forEach((blog) => {
    const card = document.createElement("a");
    const source = getBlogSource(blog.title);
    const sourceLabel = document.createElement("span");
    const title = document.createElement("h3");
    const action = document.createElement("span");

    card.className = "blog-card reveal";
    card.href = blog.url;
    card.target = "_blank";
    card.rel = "noopener noreferrer";

    sourceLabel.className = "blog-source";
    sourceLabel.textContent = source || "Media Coverage";

    title.textContent = blog.title;

    action.className = "blog-read-more";
    action.textContent = "Read More";

    card.append(sourceLabel, title, action);
    blogGrid.appendChild(card);
  });

  if (typeof observeReveals === "function") observeReveals();
}

if (blogGrid) {
  const uniqueBlogs = getUniqueBlogs(blogLinks);
  renderBlogs(uniqueBlogs);

  const filterBlogs = () => {
    const query = blogSearchInput.value.toLowerCase().trim();
    const filtered = uniqueBlogs.filter((blog) => blog.title.toLowerCase().includes(query));
    renderBlogs(filtered);
  };

  blogSearchInput?.addEventListener("input", filterBlogs);
  blogSearchInput?.addEventListener("search", filterBlogs);
  blogSearchInput?.addEventListener("change", filterBlogs);
}
