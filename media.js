function createPressLightbox() {
  const lightbox = document.createElement("div");
  const content = document.createElement("div");
  const close = document.createElement("button");
  const image = document.createElement("img");

  lightbox.className = "press-lightbox";
  lightbox.setAttribute("aria-hidden", "true");
  lightbox.setAttribute("role", "dialog");
  lightbox.setAttribute("aria-label", "Press image preview");

  content.className = "press-lightbox-content";
  close.className = "press-lightbox-close";
  close.type = "button";
  close.setAttribute("aria-label", "Close press image preview");
  close.textContent = "x";

  content.append(close, image);
  lightbox.appendChild(content);
  document.body.appendChild(lightbox);

  function closeLightbox() {
    lightbox.classList.remove("is-open");
    lightbox.setAttribute("aria-hidden", "true");
    image.removeAttribute("src");
    image.removeAttribute("alt");
  }

  function openLightbox(src, alt) {
    image.src = src;
    image.alt = alt;
    lightbox.classList.add("is-open");
    lightbox.setAttribute("aria-hidden", "false");
    close.focus();
  }

  close.addEventListener("click", closeLightbox);
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) closeLightbox();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && lightbox.classList.contains("is-open")) {
      closeLightbox();
    }
  });

  return { openLightbox };
}

